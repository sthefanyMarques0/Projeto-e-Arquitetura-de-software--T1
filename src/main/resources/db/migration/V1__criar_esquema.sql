-- Esquema completo. Datas sem fuso, interpretadas em America/Sao_Paulo.

CREATE TABLE aeroportos (
    codigo VARCHAR(10) PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    vagas INTEGER NOT NULL,
    CONSTRAINT ck_vagas_aeroporto CHECK (vagas >= 0)
);

-- Aerovias são imutáveis: a API não oferece alteração nem exclusão.
CREATE TABLE aerovias (
    id VARCHAR(20) PRIMARY KEY,
    origem_codigo VARCHAR(10) NOT NULL REFERENCES aeroportos (codigo),
    destino_codigo VARCHAR(10) NOT NULL REFERENCES aeroportos (codigo),
    distancia_km NUMERIC(38, 2) NOT NULL,
    CONSTRAINT ck_distancia_aerovia CHECK (distancia_km > 0),
    CONSTRAINT ck_aerovia_orientada CHECK (origem_codigo <> destino_codigo)
);

CREATE TABLE pilotos (
    id BIGINT PRIMARY KEY,
    nome VARCHAR(255) NOT NULL
);

CREATE TABLE aeronaves (
    prefixo VARCHAR(255) PRIMARY KEY,
    categoria VARCHAR(255) NOT NULL,
    velocidade_cruzeiro_km_h NUMERIC(38, 2) NOT NULL,
    autonomia_nominal_km NUMERIC(38, 2) NOT NULL,
    empresa_manutencao VARCHAR(255),
    companhia_aerea VARCHAR(255),
    capacidade_maxima_passageiros INTEGER,
    capacidade_maxima_toneladas NUMERIC(38, 2),
    CONSTRAINT ck_categoria_aeronave CHECK (
        categoria IN ('PARTICULAR', 'COMERCIAL_PASSAGEIROS', 'COMERCIAL_CARGA')),
    CONSTRAINT ck_dados_categoria CHECK (
        (categoria = 'PARTICULAR' AND empresa_manutencao IS NOT NULL
            AND companhia_aerea IS NULL AND capacidade_maxima_passageiros IS NULL
            AND capacidade_maxima_toneladas IS NULL)
        OR (categoria = 'COMERCIAL_PASSAGEIROS' AND companhia_aerea IS NOT NULL
            AND capacidade_maxima_passageiros IS NOT NULL AND empresa_manutencao IS NULL
            AND capacidade_maxima_toneladas IS NULL)
        OR (categoria = 'COMERCIAL_CARGA' AND companhia_aerea IS NOT NULL
            AND capacidade_maxima_toneladas IS NOT NULL AND empresa_manutencao IS NULL
            AND capacidade_maxima_passageiros IS NULL))
);

CREATE TABLE planos_de_voo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    piloto_id BIGINT NOT NULL REFERENCES pilotos (id),
    aeronave_prefixo VARCHAR(255) NOT NULL REFERENCES aeronaves (prefixo),
    origem_codigo VARCHAR(10) NOT NULL REFERENCES aeroportos (codigo),
    destino_codigo VARCHAR(10) NOT NULL REFERENCES aeroportos (codigo),
    partida_prevista TIMESTAMP NOT NULL,
    situacao VARCHAR(20) NOT NULL,
    CONSTRAINT ck_situacao_plano CHECK (situacao IN ('EM_EDICAO', 'APROVADO', 'CANCELADO', 'ABANDONADO'))
);

-- Trechos fazem parte do agregado do plano; a ordem define a sequência do percurso.
CREATE TABLE trechos (
    plano_id BIGINT NOT NULL REFERENCES planos_de_voo (id),
    ordem INTEGER NOT NULL,
    aerovia_id VARCHAR(20) NOT NULL REFERENCES aerovias (id),
    altitude INTEGER NOT NULL,
    entrada_prevista TIMESTAMP NOT NULL,
    chegada_prevista TIMESTAMP NOT NULL,
    tipo_passagem VARCHAR(20) NOT NULL,
    permanencia_minutos INTEGER,
    vaga_pretendida INTEGER,
    PRIMARY KEY (plano_id, ordem),
    CONSTRAINT ck_tipo_passagem CHECK (tipo_passagem IN ('SOBREVOO', 'POUSO')),
    CONSTRAINT ck_dados_pouso CHECK (
        (tipo_passagem = 'POUSO' AND permanencia_minutos >= 1 AND vaga_pretendida IS NOT NULL)
        OR (tipo_passagem = 'SOBREVOO' AND permanencia_minutos IS NULL AND vaga_pretendida IS NULL))
);

-- Uma linha por recurso e slot de uma hora (inicio_slot na hora cheia).
-- As restrições UNIQUE garantem, no próprio banco, que nenhum recurso seja reservado
-- duas vezes no mesmo slot, mesmo com aprovações simultâneas.
CREATE TABLE reservas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plano_id BIGINT NOT NULL REFERENCES planos_de_voo (id),
    tipo VARCHAR(20) NOT NULL,
    aerovia_id VARCHAR(20) REFERENCES aerovias (id),
    altitude INTEGER,
    aeroporto_codigo VARCHAR(10) REFERENCES aeroportos (codigo),
    vaga INTEGER,
    inicio_slot TIMESTAMP NOT NULL,
    CONSTRAINT ck_tipo_reserva CHECK (
        (tipo = 'ALTITUDE_AEROVIA' AND aerovia_id IS NOT NULL AND altitude IS NOT NULL
            AND aeroporto_codigo IS NULL AND vaga IS NULL)
        OR (tipo = 'VAGA_AEROPORTO' AND aeroporto_codigo IS NOT NULL AND vaga IS NOT NULL
            AND aerovia_id IS NULL AND altitude IS NULL)),
    CONSTRAINT uk_reserva_altitude UNIQUE (aerovia_id, altitude, inicio_slot),
    CONSTRAINT uk_reserva_vaga UNIQUE (aeroporto_codigo, vaga, inicio_slot)
);

CREATE INDEX ix_reservas_slot ON reservas (inicio_slot);
CREATE INDEX ix_reservas_plano ON reservas (plano_id);
